const int LEDfontSize = sizeof(LEDfont) / sizeof(LEDChar);

int LEDlookup(char k){
  for(int i=0;i<LEDfontSize;i++){
    if(k==LEDfont[i].key){
      return i;
    }
  }
  return -1; // Character not found
}

